//! Deterministic Zig provider emission. Input must be a validated Document.
const std = @import("std");
const m = @import("token_model");
const A = std.mem.Allocator;

pub fn generate(allocator: A, doc: *const m.Document) ![]u8 {
    if (doc.diagnostic != null) return error.InvalidDocument;
    var arena = std.heap.ArenaAllocator.init(allocator);
    defer arena.deinit();
    var e: Emitter = .{ .a = arena.allocator(), .doc = doc };
    try e.run();
    return allocator.dupe(u8, e.out.items);
}

const Emitter = struct {
    a: A,
    doc: *const m.Document,
    out: std.ArrayList(u8) = .empty,
    fn put(e: *Emitter, text: []const u8) !void {
        try e.out.appendSlice(e.a, text);
    }
    fn fmt(e: *Emitter, comptime format: []const u8, args: anytype) !void {
        try e.put(try std.fmt.allocPrint(e.a, format, args));
    }
    fn id(e: *Emitter, name: []const u8) !void {
        try e.fmt("@\"{s}\"", .{name});
    }
    fn fieldPath(e: *Emitter, path: []const u8) !void {
        var it = std.mem.splitScalar(u8, path, '.');
        while (it.next()) |part| {
            try e.put(".");
            try e.id(part);
        }
    }
    fn literal(e: *Emitter, x: m.Value) !void {
        switch (x) {
            .number => |v| try e.fmt("{d}", .{v}),
            .weight => |v| try e.fmt("{d}", .{v}),
            .color => |v| try e.fmt(".{{ .r = {d}, .g = {d}, .b = {d}, .a = {d} }}", .{ v.r, v.g, v.b, v.a }),
            .shadow => |v| {
                try e.put(".{ .color = ");
                try e.literal(.{ .color = v.color });
                try e.fmt(", .blur = {d}, .spread = {d}, .offset_x = {d}, .offset_y = {d} }}", .{ v.blur, v.spread, v.offset_x, v.offset_y });
            },
            .typography => |v| {
                try e.put(".{");
                inline for (@import("zenit_reflection").fields(@TypeOf(v))) |f| if (@field(v, f.name)) |n| {
                    try e.fmt(" .{s} = {d},", .{ f.name, n });
                };
                try e.put(" }");
            },
        }
    }
    const TreeKind = enum { types, refs, values };
    fn tree(e: *Emitter, prefix: []const u8, kind: TreeKind, mode: ?usize) anyerror!void {
        try e.put(if (kind == .values) ".{\n" else "struct {\n");
        var previous: ?[]const u8 = null;
        for (e.doc.tokens, 0..) |tok, index| {
            if (!std.mem.startsWith(u8, tok.path, prefix)) continue;
            const rest = tok.path[prefix.len..];
            const end = std.mem.indexOfScalar(u8, rest, '.') orelse rest.len;
            const name = rest[0..end];
            if (previous) |p| if (std.mem.eql(u8, p, name)) continue;
            previous = name;
            if (kind == .refs) try e.put("pub const ") else if (kind == .values) try e.put(".");
            try e.id(name);
            try e.put(if (kind == .types) ": " else " = ");
            if (end < rest.len) {
                const child = try std.fmt.allocPrint(e.a, "{s}{s}.", .{ prefix, name });
                try e.tree(child, kind, mode);
            } else switch (kind) {
                .types => try e.fmt("sv.Value(.{s})", .{@tagName(tok.category)}),
                .values => try e.literal(e.doc.modes[mode.?].values[index]),
                .refs => {
                    const relative = tok.path[@tagName(tok.category).len + 1 ..];
                    try e.fmt("@as(Token(.{s}), .", .{@tagName(tok.category)});
                    try e.id(relative);
                    try e.put(")");
                },
            }
            try e.put(if (kind == .refs) ";\n" else ",\n");
        }
        try e.put("}");
    }
    fn run(e: *Emitter) !void {
        try e.put("// Generated by zenit-tokens v1. Do not edit.\nconst sv = @import(\"zenit_style_values\");\npub const Category = sv.Category;\npub const format_version = 1;\n");
        try e.put("pub const Mode = enum {\n");
        for (e.doc.modes) |mode| {
            try e.id(mode.name);
            try e.put(",\n");
        }
        try e.put("};\npub fn Token(comptime category: Category) type { return switch (category) {\n");
        inline for (@import("zenit_reflection").fields(m.Category)) |f| {
            try e.fmt(".{s} => {s}Token,\n", .{ f.name, f.name });
        }
        try e.put("}; }\n");
        inline for (@import("zenit_reflection").fields(m.Category)) |f| {
            try e.fmt("const {s}Token = enum {{\n", .{f.name});
            for (e.doc.tokens) |tok| if (tok.category == @field(m.Category, f.name)) {
                try e.id(tok.path[f.name.len + 1 ..]);
                try e.put(",\n");
            };
            try e.put("};\n");
        }
        try e.put("pub const Tokens = struct {\n");
        inline for (@import("zenit_reflection").fields(m.Category)) |f| {
            try e.fmt("{s}: ", .{f.name});
            try e.tree(f.name ++ ".", .types, null);
            try e.put(",\n");
        }
        try e.put("};\npub const refs = struct {\n");
        inline for (@import("zenit_reflection").fields(m.Category)) |f| {
            try e.fmt("pub const {s} = ", .{f.name});
            try e.tree(f.name ++ ".", .refs, null);
            try e.put(";\n");
        }
        try e.put("};\npub const Values = struct { name: []const u8, scheme: sv.ColorScheme, tokens: Tokens };\n");
        try e.put("pub fn resolve(comptime category: Category, ref: Token(category), t: *const Values) sv.Value(category) {\n");
        if (e.doc.tokens.len == 0) try e.put("_ = t;\n");
        try e.put("return switch (category) {\n");
        inline for (@import("zenit_reflection").fields(m.Category)) |f| {
            try e.fmt(".{s} => switch (ref) {{\n", .{f.name});
            for (e.doc.tokens) |tok| if (tok.category == @field(m.Category, f.name)) {
                try e.put(".");
                try e.id(tok.path[f.name.len + 1 ..]);
                try e.put(" => t.tokens");
                try e.fieldPath(tok.path);
                try e.put(",\n");
            };
            try e.put("},\n");
        }
        try e.put("}; }\npub const modes = struct {\n");
        for (e.doc.modes, 0..) |mode, mi| {
            try e.put("pub const ");
            try e.id(mode.name);
            try e.put(" = Values{\n");
            try e.fmt(".name = \"{s}\", .scheme = .{s},\n.tokens = .{{\n", .{ mode.name, @tagName(mode.scheme) });
            inline for (@import("zenit_reflection").fields(m.Category)) |f| {
                try e.fmt(".{s} = ", .{f.name});
                try e.tree(f.name ++ ".", .values, mi);
                try e.put(",\n");
            }
            try e.put("},\n};\n");
        }
        try e.put("};\npub const metadata = [_]struct { path: []const u8, source: []const u8, pointer: []const u8 }{\n");
        for (e.doc.tokens) |tok| {
            try e.fmt(".{{ .path = \"{s}\", .source = \"{s}\", .pointer = \"{s}\" }},\n", .{ tok.path, tok.source_path, tok.pointer });
        }
        try e.put("};\n");
    }
};
