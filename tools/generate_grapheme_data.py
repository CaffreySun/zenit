#!/usr/bin/env python3
"""Generate compact Zig lookup tables for Unicode grapheme segmentation.

The input files are vendored, immutable Unicode Character Database 17.0.0
artifacts.  Regeneration is deterministic and deliberately has no network
access; updating Unicode is a reviewed source-data change.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import subprocess
import sys
import tempfile


UNICODE_VERSION = "17.0.0"
GCB_NAMES = {
    "CR": "cr",
    "LF": "lf",
    "Control": "control",
    "Extend": "extend",
    "ZWJ": "zwj",
    "Regional_Indicator": "regional_indicator",
    "Prepend": "prepend",
    "SpacingMark": "spacing_mark",
    "L": "l",
    "V": "v",
    "T": "t",
    "LV": "lv",
    "LVT": "lvt",
}
INCB_NAMES = {"Consonant": "consonant", "Extend": "extend", "Linker": "linker"}
RANGE_RE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([^#]+)")


def records(path: Path):
    text = path.read_text(encoding="utf-8")
    header = "\n".join(text.splitlines()[:10])
    if UNICODE_VERSION not in header and "Version: 17.0" not in header:
        raise ValueError(f"{path}: expected Unicode {UNICODE_VERSION} header")
    for line_number, line in enumerate(text.splitlines(), 1):
        match = RANGE_RE.match(line)
        if not match:
            continue
        start = int(match.group(1), 16)
        end = int(match.group(2) or match.group(1), 16)
        fields = [field.strip() for field in match.group(3).split(";")]
        yield line_number, start, end, fields


def merge_ranges(items):
    merged = []
    for start, end, value in sorted(items):
        if merged and merged[-1][2] == value and merged[-1][1] + 1 == start:
            merged[-1] = (merged[-1][0], end, value)
        else:
            merged.append((start, end, value))
    return merged


def emit_ranges(name: str, value_type: str, items) -> str:
    lines = [f"const {name} = [_]Range({value_type}){{"]
    for start, end, value in merge_ranges(items):
        lines.append(f"    .{{ .start = 0x{start:X}, .end = 0x{end:X}, .value = .{value} }},")
    lines.append("};")
    return "\n".join(lines)


def generate(source_root: Path) -> str:
    gcb = []
    for line, start, end, fields in records(source_root / "GraphemeBreakProperty.txt"):
        if len(fields) != 1 or fields[0] not in GCB_NAMES:
            raise ValueError(f"GraphemeBreakProperty.txt:{line}: unsupported value {fields!r}")
        gcb.append((start, end, GCB_NAMES[fields[0]]))

    ext_pict = []
    for _, start, end, fields in records(source_root / "emoji-data.txt"):
        if fields == ["Extended_Pictographic"]:
            ext_pict.append((start, end, "yes"))

    incb = []
    for line, start, end, fields in records(source_root / "DerivedCoreProperties.txt"):
        if not fields or fields[0] != "InCB":
            continue
        if len(fields) != 2 or fields[1] not in INCB_NAMES:
            raise ValueError(f"DerivedCoreProperties.txt:{line}: unsupported InCB value {fields!r}")
        incb.append((start, end, INCB_NAMES[fields[1]]))

    pieces = [
        "// Generated by tools/generate_grapheme_data.py; DO NOT EDIT.",
        f'pub const unicode_version = "{UNICODE_VERSION}";',
        "",
        "pub const Gcb = enum(u8) { other, cr, lf, control, extend, zwj, regional_indicator, prepend, spacing_mark, l, v, t, lv, lvt };",
        "pub const InCB = enum(u8) { none, consonant, extend, linker };",
        "const Bool = enum(u1) { no, yes };",
        "",
        "fn Range(comptime T: type) type { return struct { start: u21, end: u21, value: T }; }",
        "fn lookup(comptime T: type, cp: u21, ranges: []const Range(T), fallback: T) T {",
        "    var low: usize = 0;",
        "    var high: usize = ranges.len;",
        "    while (low < high) {",
        "        const mid = low + (high - low) / 2;",
        "        const range = ranges[mid];",
        "        if (cp < range.start) high = mid else if (cp > range.end) low = mid + 1 else return range.value;",
        "    }",
        "    return fallback;",
        "}",
        "",
        emit_ranges("gcb_ranges", "Gcb", gcb),
        "",
        emit_ranges("extended_pictographic_ranges", "Bool", ext_pict),
        "",
        emit_ranges("incb_ranges", "InCB", incb),
        "",
        "pub fn gcb(cp: u21) Gcb { return lookup(Gcb, cp, &gcb_ranges, .other); }",
        "pub fn isExtendedPictographic(cp: u21) bool { return lookup(Bool, cp, &extended_pictographic_ranges, .no) == .yes; }",
        "pub fn incb(cp: u21) InCB { return lookup(InCB, cp, &incb_ranges, .none); }",
        "",
    ]
    return "\n".join(pieces)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=Path("vendor/unicode") / UNICODE_VERSION)
    parser.add_argument("--output", type=Path, default=Path("src/text_core/grapheme_data_generated.zig"))
    parser.add_argument("--test-output", type=Path, default=Path("src/text_core/testdata/GraphemeBreakTest-17.0.0.txt"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = generate(args.source)
    rendered_test = (args.source / "GraphemeBreakTest.txt").read_text(encoding="utf-8")
    if args.check:
        with tempfile.TemporaryDirectory() as directory:
            candidate = Path(directory) / args.output.name
            candidate.write_text(rendered, encoding="utf-8")
            subprocess.run(["zig", "fmt", str(candidate)], check=True, capture_output=True)
            formatted = candidate.read_text(encoding="utf-8")
        if (not args.output.exists() or args.output.read_text(encoding="utf-8") != formatted or
                not args.test_output.exists() or args.test_output.read_text(encoding="utf-8") != rendered_test):
            print(f"stale generated file: {args.output}", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(rendered, encoding="utf-8")
    subprocess.run(["zig", "fmt", str(args.output)], check=True, capture_output=True)
    args.test_output.parent.mkdir(parents=True, exist_ok=True)
    args.test_output.write_text(rendered_test, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
